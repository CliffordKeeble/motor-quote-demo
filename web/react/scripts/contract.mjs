// Generates the TypeScript types from contracts/openapi.yaml into web/shared/api.d.ts, the one
// place both front ends, web/react and web/angular, import them from.
//
//   npm run contract         writes web/shared/api.d.ts
//   npm run contract:check   writes nothing; exits 1 if the committed file differs from what the
//                            contract generates. The pipeline runs this.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const spec = new URL('../../../contracts/openapi.yaml', import.meta.url);
const target = new URL('../../shared/api.d.ts', import.meta.url);

const banner = `/**
 * GENERATED by openapi-typescript from contracts/openapi.yaml. Do not edit by hand.
 * Regenerate with \`npm run contract\` in web/react.
 */

`;

const generated = banner + astToString(await openapiTS(spec)).replaceAll('\r\n', '\n');

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(target, 'utf8').replaceAll('\r\n', '\n');
  } catch {
    // A missing file is a difference.
  }
  if (committed !== generated) {
    console.error(`${fileURLToPath(target)} is out of date with contracts/openapi.yaml.`);
    console.error('Run `npm run contract` in web/react and commit the result.');
    process.exit(1);
  }
  console.log('contract types are up to date');
} else {
  writeFileSync(target, generated);
  console.log(`wrote ${fileURLToPath(target)}`);
}
